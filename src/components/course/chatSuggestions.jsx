// اقتراحات سريعة تتغير حسب آخر رد من المساعد

const DEFAULT_PROMPTS = [
  "لخّصلي أهم النقاط",
  "اعملي 5 أسئلة كويز",
  "لوّنلي المحتوى",
  "إيه أهم حاجة للامتحان؟",
  "اشرحلي بمثال",
];

export function getSuggestions(lastAssistantText = "") {
  const t = (lastAssistantText || "").toLowerCase();

  // بعد كويز
  if (/[1-5][).．]|سؤال|اختر|إجابة|mcq/i.test(lastAssistantText)) {
    return ["صحّحلي الإجابات", "اعملي أسئلة أصعب", "اشرح إجابة كل سؤال", "اعملي 5 كمان"];
  }
  // بعد ملخص أو نقاط
  if (/[-•]|ملخص|أهم|نقاط/.test(lastAssistantText)) {
    return ["بسّطها أكتر", "اعملي كويز على الملخص", "اديني أمثلة", "حوّلها بطاقات مراجعة"];
  }
  // بعد شرح
  if (t.length > 200) {
    return ["لخّصلي اللي فات", "اديني مثال تاني", "اعملي سؤال على ده", "إيه الخلاصة؟"];
  }
  return DEFAULT_PROMPTS;
}