export function getProgressMsg(done, total) {
  if (total === 1) {
    const messages = ['الـ AI بيقرأ المحاضرة بالكامل... 🔍', 'بيستخرج كل الفيتشرز والنقاط المهمة... ✨', 'بيرتّب الملخص حسب نسبة التغطية... 📚', 'مراجعة أخيرة للتغطية... ⚡'];
    return messages[Math.min(done, messages.length - 1)];
  }
  return `جزء ${done + 1} من ${total} — ${Math.round(((done + 1) / total) * 100)}% ✨`;
}

export function getGenerationOptions(choices, languageMode, summaryStyle) {
  const language = choices.language || languageMode;
  const style = choices.style || summaryStyle;
  const sizeTier = getSummarySizeTier(choices.sizeTier || style);
  const colorLevel = 'none';
  const colorize = false;
  const subject = getSubjectType(choices.subjectType || 'auto');
  const sizeRule = SIZE_TIER_PROMPT_RULES[sizeTier.id] || SIZE_TIER_PROMPT_RULES.medium;

  return {
    language,
    style,
    sizeTier: sizeTier.id,
    coverageRange: sizeTier.coverageRange,
    colorLevel,
    colorize,
    formatOnly: style === 'format_only',
    languageRule: LANGUAGE_RULES[language] || LANGUAGE_RULES.bilingual,
    styleRule: `${getSummaryTemplate(style)?.prompt || STYLE_RULES[style] || STYLE_RULES.lecture_exact}\n${sizeRule}`,
    subject,
    noColorRule: NO_COLOR_RULE,
    agentRules: AGENT_RULES,
    contentFormatRule: `- اجعل الكلمات والمصطلحات المهمة Bold باستخدام **الكلمة**.\n- ${NO_COLOR_RULE}\n- استخدم عناوين Markdown (## و ###) لتقسيم الأفكار الفرعية بوضوح، واذكر كل الفيتشرز والنقاط الفرعية بالكامل.`,
  };
}

